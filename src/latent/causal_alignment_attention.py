"""Causal-alignment training losses for LatentModel, adapted from CASE
(arXiv:2607.18820) "Causal Alignment and Structural Enforcement" for
faithful chain-of-thought. Does not modify layers.py, reasoning_dataset.py,
or latent_attention_train.py. Additive only: delete this file plus
latent_attention_train_causal.py to remove the approach.

CASE maps instruction Z / CoT X / answer Y onto our history x / thought r /
target y, and trains three auxiliary losses alongside the standard joint
objective, each isolating a different causal quantity. We adapt two of the
three -- the third, L_X-int, pairs the *same* input with a genuinely valid
*different* (CoT, answer) pair generated by a stronger external model; we
have no such oracle for recommendation (no external model can generate a
valid alternate "this history really does lead to item Y'" pair), so it is
dropped for this attempt (see avoid_reasoning_collapse_and_shortcut_learning.md,
Attempt 4).

L_main   = -log p(y | x, r)                         -- standard joint loss, unrestricted attention
L_Zdrop  = -log p(y | r, history hidden)             -- our adaptation of CASE's L_Z-drop:
           forces r ALONE to be sufficient to predict y, added as a permanent
           auxiliary loss every step (not an annealed curriculum phase, unlike
           Attempt 1's schedule). Reuses the exact "reasoning_only" attention
           bias validated in scheduled_attention.py.
L_Zint   = -log p(y | x_poisoned, r)                 -- our adaptation of CASE's L_Z-int:
           CASE poisons the instruction with a fixed adversarial suggestion
           ("An MIT professor believes the answer is {wrong}") while keeping
           the correct (CoT, answer) fixed, training the model to predict the
           true answer despite the injected bias. We have no natural-language
           slot to inject a textual claim into mid-training, so we approximate
           the same spirit at the embedding level: splice another example's
           thought vector (detached, borrowed via the same roll-and-splice
           trick as the margin/contrastive attempts) into a history-region
           position (the token immediately preceding the thought token, which
           is always real content, not padding) -- a plausible-looking but
           wrong "pooled summary" signal sitting in the history stream -- while
           keeping the correct r in its normal slot and the true labels
           unchanged. This directly tests whether the decoder can be misled by
           a confusing signal in the history stream when the correct r is
           still available in its usual place.

L_train = L_main + zdrop_weight * L_Zdrop + zint_weight * L_Zint

No margin, no temperature -- every term is plain NLL, matching CASE.
"""

import torch
import torch.nn.functional as F
from transformers import Qwen2ForCausalLM
from transformers.modeling_outputs import CausalLMOutputWithPast

from layers import LatentModel


class CausalAlignmentLatentModel(LatentModel):
    def __init__(self, config):
        super().__init__(config)
        self.zdrop_weight = 1.0
        self.zint_weight = 1.0
        # See margin_loss_attention.py for why this is necessary: Trainer will
        # not divide our custom loss by gradient_accumulation_steps on its own.
        self.grad_accum_steps = 1
        self.last_main_loss = None
        self.last_zdrop_loss = None
        self.last_zint_loss = None

    def _thought_positions(self, input_ids: torch.LongTensor) -> torch.LongTensor:
        thought_token_id = self.model.embed_tokens.num_embeddings - 1
        where = torch.nonzero(input_ids == thought_token_id)
        idx = torch.zeros(input_ids.size(0), dtype=torch.long, device=input_ids.device)
        idx[where[:, 0]] = where[:, 1]
        return idx

    @staticmethod
    def _per_example_nll(logits: torch.Tensor, labels: torch.Tensor) -> torch.Tensor:
        shift_logits = logits[:, :-1, :].contiguous()
        shift_labels = labels[:, 1:].contiguous()
        token_nll = F.cross_entropy(
            shift_logits.view(-1, shift_logits.size(-1)).float(),
            shift_labels.view(-1),
            ignore_index=-100,
            reduction="none",
        ).view(shift_labels.size())
        mask = (shift_labels != -100).float()
        return (token_nll * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1.0)

    def _reasoning_only_bias(
        self, attention_mask: torch.Tensor, thought_idx: torch.LongTensor, dtype: torch.dtype
    ) -> torch.Tensor:
        """Target queries can attend to the thought token and each other, but
        not to history -- see scheduled_attention.py's identical mode, kept in
        sync here for L_Zdrop."""
        batch_size, seq_len = attention_mask.shape
        device = attention_mask.device

        causal = torch.tril(torch.ones(seq_len, seq_len, dtype=torch.bool, device=device))
        key_valid = attention_mask.bool()
        allowed = causal.unsqueeze(0) & key_valid.unsqueeze(1)

        pos = torch.arange(seq_len, device=device).unsqueeze(0)
        thought_pos = thought_idx.unsqueeze(1)
        is_history_key = pos < thought_pos
        is_target_query = pos >= thought_pos

        block = is_target_query.unsqueeze(2) & is_history_key.unsqueeze(1)
        allowed = allowed & (~block)

        bias = torch.zeros(batch_size, seq_len, seq_len, dtype=dtype, device=device)
        bias = bias.masked_fill(~allowed, torch.finfo(dtype).min)
        return bias.unsqueeze(1)

    def _run_second_pass(self, embeds, attention_mask, position_ids, cache_position, num_logits_to_keep):
        return Qwen2ForCausalLM.forward(
            self,
            inputs_embeds=embeds,
            attention_mask=attention_mask,
            position_ids=position_ids,
            past_key_values=None,
            use_cache=False,
            output_attentions=False,
            output_hidden_states=False,
            return_dict=True,
            cache_position=cache_position,
            num_logits_to_keep=num_logits_to_keep,
        )

    def forward(
        self,
        input_ids: torch.LongTensor = None,
        attention_mask=None,
        position_ids=None,
        past_key_values=None,
        inputs_embeds=None,
        labels=None,
        use_cache=None,
        output_attentions=None,
        output_hidden_states=None,
        return_dict=None,
        cache_position=None,
        num_logits_to_keep: int = 0,
        **kwargs,
    ):
        is_prefill = (
            input_ids is not None
            and inputs_embeds is None
            and attention_mask is not None
            and input_ids.size() == attention_mask.size()
        )

        if not (is_prefill and self.training and labels is not None):
            # eval / generation / no-label calls: identical to vanilla LatentModel
            return super().forward(
                input_ids=input_ids,
                attention_mask=attention_mask,
                position_ids=position_ids,
                past_key_values=past_key_values,
                inputs_embeds=inputs_embeds,
                labels=labels,
                use_cache=use_cache,
                output_attentions=output_attentions,
                output_hidden_states=output_hidden_states,
                return_dict=return_dict,
                cache_position=cache_position,
                num_logits_to_keep=num_logits_to_keep,
                **kwargs,
            )

        thought_idx = self._thought_positions(input_ids)
        pos_embeds = self.generate_embs(input_ids, attention_mask)
        batch_size = pos_embeds.size(0)
        batch_idx = torch.arange(batch_size, device=pos_embeds.device)

        # L_main: standard unrestricted ("both") attention, correct r, true y
        main_out = self._run_second_pass(pos_embeds, attention_mask, position_ids, cache_position, num_logits_to_keep)
        main_nll = self._per_example_nll(main_out.logits, labels)
        main_loss = main_nll.mean()

        # L_Zdrop: history hidden from target queries, correct r, true y
        zdrop_bias = self._reasoning_only_bias(attention_mask, thought_idx, pos_embeds.dtype)
        zdrop_out = self._run_second_pass(pos_embeds, zdrop_bias, position_ids, cache_position, num_logits_to_keep)
        zdrop_nll = self._per_example_nll(zdrop_out.logits, labels)
        zdrop_loss = zdrop_nll.mean()

        # L_Zint: another example's r poisoned into a history-region position,
        # correct r kept at the thought position, unrestricted attention, true y
        if batch_size > 1:
            perm = torch.roll(batch_idx, shifts=1)
            poison_r = pos_embeds[perm, thought_idx[perm]].detach()
            inject_pos = (thought_idx - 1).clamp(min=0)
            zint_embeds = pos_embeds.clone()
            zint_embeds[batch_idx, inject_pos] = poison_r
            zint_out = self._run_second_pass(zint_embeds, attention_mask, position_ids, cache_position, num_logits_to_keep)
            zint_nll = self._per_example_nll(zint_out.logits, labels)
            zint_loss = zint_nll.mean()
        else:
            zint_loss = main_nll.new_zeros(())

        self.last_main_loss = main_loss.detach()
        self.last_zdrop_loss = zdrop_loss.detach()
        self.last_zint_loss = zint_loss.detach()

        total_loss = (main_loss + self.zdrop_weight * zdrop_loss + self.zint_weight * zint_loss) / self.grad_accum_steps

        return CausalLMOutputWithPast(
            loss=total_loss,
            logits=main_out.logits,
            past_key_values=main_out.past_key_values,
            hidden_states=main_out.hidden_states,
            attentions=main_out.attentions,
        )
